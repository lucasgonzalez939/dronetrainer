import {
  THREE, scene,
  levelObjects, setLevelObjects,
  obstacles, setObstacles,
  levelSlickZones, setLevelSlickZones,
  levelGates, setLevelGates,
  levelLandingPad, setLevelLandingPad,
  movingGate, setMovingGate,
  softCheckpoints, setSoftCheckpoints,
  missions, setMissions,
  setWindVector,
  createFlightGate, createLandingPad, createSlickZone,
  createSoftCheckpoint, createWaypoint, createInspectionTower,
  createGhostDrone, checkGatePass
} from '../common.js';

export const level = {
  name: "DESAFÍO 15",
  subtitle: "El Coliseo Infinito (Procedural Gauntlet)",
  desc: "El desafío supremo definitivo: circuito procedural infinito con aro móvil, turbulencia de tormenta y suelo deslizante generados de cero en cada intento.",
  objectives: [
    "Circuito procedural supremo: compuertas y obstáculos generados al azar",
    "Intercepta la compuerta dinámica en trayectoria sincronizada",
    "Supera el viento de tormenta y aterriza en el Helipuerto Dorado"
  ],
  isChallenge: true,
  isAutoGenerated: true,
  medalTimes: { gold: 38, silver: 54, bronze: 78 },
  windScale: 2.2,
  windDir: new THREE.Vector3(0.6, 0, 0.3),
  hazards: { vpsOn: true, windOn: true, windStrength: 2.2, turbOn: true, turbStrength: 1.5 },
  setup() {
    // Randomized wind vector each attempt
    const wAngle = Math.random() * Math.PI * 2;
    const wForce = 2.0 + Math.random() * 1.2;
    const wVec = new THREE.Vector3(Math.cos(wAngle), 0, Math.sin(wAngle)).multiplyScalar(wForce);
    setWindVector(wVec);

    // Random slick zone
    const slick = createSlickZone((Math.random() - 0.5) * 4, -16.0, 7.0, 8.0);
    setLevelSlickZones([slick]);

    const gates = [];
    const gateCount = 6;
    let dynamicGate = null;

    for (let i = 0; i < gateCount; i++) {
      const gz = -4.5 - i * 4.2;
      const gx = (Math.random() - 0.5) * 4.5;
      const gy = 1.1 + Math.random() * 1.5;
      const rotY = (Math.random() - 0.5) * 0.45;
      const g = createFlightGate(gx, gy, gz, rotY, 1.2);

      // Make gate 3 moving
      if (i === 2) {
        g.speed = 1.0 + Math.random() * 0.4;
        g.amplitude = 2.8 + Math.random() * 0.8;
        g.phase = Math.random() * Math.PI;
        dynamicGate = g;
      }
      gates.push(g);
    }

    setLevelGates(gates);
    if (dynamicGate) {
      setMovingGate(dynamicGate);
    }

    // Mid checkpoint
    const cp = createSoftCheckpoint(0.0, 1.5, -15.0, 0, 1.3);
    setSoftCheckpoints([cp]);

    const padZ = -4.5 - gateCount * 4.2 - 2.5;
    const pad = createLandingPad(0.0, padZ, 0xffd700);
    setLevelLandingPad(pad);

    const total = gates.length + 2; // gates + checkpoint + landing
    const newMissions = [];

    gates.forEach((g, idx) => {
      if (idx === 3) {
        // Checkpoint before gate 4
        newMissions.push({
          title: "CHECKPOINT",
          desc: "Baliza de guardado de emergencia",
          target: cp.center,
          check: () => cp.check(),
          onComplete: () => cp.setActivated()
        });
      }
      newMissions.push({
        title: g === dynamicGate ? `⚡ CINÉTICA ${idx + 1}/${total}` : `GAUNTLET ${idx + 1}/${total}`,
        desc: g === dynamicGate ? `Intercepta el Aro Móvil ${idx + 1}` : `Cruza el Aro Procedural ${idx + 1}`,
        target: g.center,
        check: () => checkGatePass(g, 0.48),
        onComplete: () => g.setSuccess(),
        hint: g === dynamicGate ? "Anticípate al desplazamiento del aro." : "Corrige la deriva del viento aleatorio."
      });
    });

    newMissions.push({
      title: `COLISEO FINAL / ${total}`,
      desc: "¡Aterriza en el Helipuerto Dorado del Campeón!",
      target: pad.center,
      check: () => false
    });

    setMissions(newMissions);
  }
};

export default level;
